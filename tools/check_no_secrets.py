#!/usr/bin/env python3
"""Refuse secrets and signing material in the working tree and in the history.

Patterns are deliberately narrow: they look for private keys, cloud credentials,
console keys and literal keystore passwords. A false positive is reported, not
hidden: this guard never edits anything.

    python3 tools/check_no_secrets.py [--history] [root]

Files scanned: when root is the top of a git work tree, every file git could commit
(tracked or staged, plus untracked files that are not ignored); otherwise every file
under root. With --history the scan also covers every blob reachable from any ref
(`git rev-list --all --objects`), with no commit limit: CI checks out with
`fetch-depth: 0` so the whole history is there. A finding in the history names the
commit that introduced the blob.

Refused, whatever the file name:
  * PEM private keys, ENCRYPTED and PGP blocks included
  * AWS, GitHub, Slack and provider API tokens
  * console key lines (header_key, key_area_key_*, titlekek_*, master_key_* = <hex>)
    and title.keys lines (<32 hex> = <32 hex>)
  * literal keystore passwords: storePassword or keyPassword "<value>" (Gradle),
    storePassword=<value> (.properties), keytool -storepass <value> and -keypass <value>,
    apksigner --ks-pass pass:<value> and --key-pass pass:<value>. A value read from the
    environment ($VAR, env:, :env) or a <placeholder> is fine, and so are the
    public throw-away passwords listed in PUBLIC_PASSWORDS (Android debug
    keystore, per-run CI key).

Exit status 0 = clean, 1 = refused.
"""
import re
import subprocess
import sys
from pathlib import Path

# Same file selection as the content guard (git-aware), so both judge the same files.
from check_no_game_content import candidate_files, is_work_tree_top

ROOT = Path(__file__).resolve().parents[1]

# Passwords that protect nothing: the Android SDK debug keystore convention and the
# per-run key generated by CI. Anything else written in clear is refused.
PUBLIC_PASSWORDS = {"android", "ci-only"}


def literal_password(match) -> bool:
    value = match.group("value").decode("utf-8", "replace").strip("\"'")
    return bool(value) and not value.startswith(("$", "%", "<")) and value not in PUBLIC_PASSWORDS


PATTERNS = [
    (re.compile(rb"-----BEGIN [A-Z ]*PRIVATE KEY(?: BLOCK)?-----"), "private key", None),
    (re.compile(rb"\bAKIA[0-9A-Z]{16}\b"), "AWS access key id", None),
    (re.compile(rb"\bghp_[A-Za-z0-9]{36}\b"), "GitHub token", None),
    (re.compile(rb"\bgithub_pat_[A-Za-z0-9_]{22,}\b"), "GitHub fine-grained token", None),
    (re.compile(rb"\bsk-[A-Za-z0-9]{32,}\b"), "provider secret key", None),
    (re.compile(rb"\bxox[baprs]-[A-Za-z0-9-]{10,}\b"), "Slack token", None),
    (re.compile(rb"prod\.keys\s*[:=]\s*[0-9a-f]{16}\b"), "console keys", None),
    (re.compile(rb"(?im)^\s*(?:header_key|key_area_key_\w+|titlekek_\w+|master_key_\w+)"
                rb"\s*=\s*[0-9a-f]{32,}"), "console keys", None),
    (re.compile(rb"(?im)^\s*[0-9a-f]{32}\s*=\s*[0-9a-f]{32}\s*$"), "title keys", None),
    (re.compile(rb"\b(?:storePassword|keyPassword)\s*(?:=|\()?\s*(?P<value>\"[^\"\n]*\"|'[^'\n]*')"),
     "literal keystore password", literal_password),
    (re.compile(rb"(?<![\w:])-(?:src|dest)?(?:storepass|keypass)\b[\"',\s]+(?P<value>[^\s\"',)]+)"),
     "literal keystore password", literal_password),
    (re.compile(rb"--(?:ks|key)-pass[\"',\s]+pass:(?P<value>[^\s\"',)}]+)"),
     "literal keystore password", literal_password),
]

# Only .properties files hold `storePassword=value` without quotes; elsewhere
# (Kotlin, Groovy) the same shape is an assignment from another variable.
PROPERTIES_PATTERN = (
    re.compile(rb"(?im)^\s*(?:storePassword|keyPassword|store\.password|key\.password)"
               rb"\s*[=:]\s*(?P<value>\S+)\s*$"),
    "literal keystore password", literal_password)

# Text files only.
BINARY_SUFFIXES = {
    ".ttf", ".otf", ".png", ".jpg", ".jpeg", ".gif", ".webp", ".ico", ".icns",
    ".pdf", ".zip", ".so", ".a", ".o", ".lib", ".exe", ".dll", ".mp3", ".ogg",
    ".wav", ".mp4", ".bin", ".dat",
}


def scan_bytes(data: bytes, label: str, findings: list) -> None:
    patterns = PATTERNS
    if label.lower().endswith(".properties"):
        patterns = PATTERNS + [PROPERTIES_PATTERN]
    for pattern, reason, accept in patterns:
        for match in pattern.finditer(data):
            if accept is None or accept(match):
                # Show where it is, never the secret itself: CI logs are public.
                line = data.count(b"\n", 0, match.start()) + 1
                before = data[max(0, match.start() - 40):match.start()].rsplit(b"\n", 1)[-1]
                snippet = before.decode("utf-8", "replace") + "<redacted>"
                findings.append((f"{label}:{line}", reason, snippet))
                break


def git(root: Path, *args, **kwargs):
    return subprocess.run(["git", "-C", str(root), *args], capture_output=True, **kwargs)


def scan_history(root: Path, findings: list) -> int:
    """Scan every blob reachable from any ref once. Return the number of blobs read."""
    if not is_work_tree_top(root):
        print(f"error: --history needs the top of a git work tree, {root} is not", file=sys.stderr)
        sys.exit(2)
    listing = git(root, "rev-list", "--all", "--objects", text=True, check=True)
    paths = {}
    for line in listing.stdout.splitlines():
        sha, _, path = line.partition(" ")
        if path and Path(path).suffix.lower() not in BINARY_SUFFIXES:
            paths.setdefault(sha, path)
    if not paths:
        return 0
    batch = git(root, "cat-file", "--batch", input="\n".join(paths).encode() + b"\n",
                check=True).stdout
    scanned, offset = 0, 0
    while offset < len(batch):
        end = batch.index(b"\n", offset)
        sha, kind, size = batch[offset:end].decode().split()
        start, size = end + 1, int(size)
        offset = start + size + 1
        if kind != "blob":
            continue
        scanned += 1
        found = []
        scan_bytes(batch[start:start + size], paths[sha], found)
        if found:
            commit = git(root, "log", "--all", "--format=%h", "--diff-filter=AM",
                         f"--find-object={sha}", text=True).stdout.split()
            where = commit[-1] if commit else sha[:10]
            findings.extend((f"{where}:{label}", reason, snippet) for label, reason, snippet in found)
    return scanned


def main(argv) -> int:
    args = [a for a in argv[1:] if a != "--history"]
    root = Path(args[0]) if args else ROOT
    if not root.is_dir():
        print(f"error: {root} is not a directory", file=sys.stderr)
        return 2
    findings = []
    scanned = 0

    for rel in candidate_files(root):
        if Path(rel).suffix.lower() in BINARY_SUFFIXES:
            continue
        try:
            data = (root / rel).read_bytes()
        except OSError:
            continue  # deleted from the work tree but still in the index
        scanned += 1
        scan_bytes(data, rel, findings)

    history = ""
    if "--history" in argv:
        history = f" and {scan_history(root, findings)} blobs of the whole history"

    if findings:
        print("REFUSED: possible secret found:", file=sys.stderr)
        for label, reason, snippet in findings:
            print(f"  {label} — {reason}\n      {snippet.strip()[:120]}", file=sys.stderr)
        return 1

    print(f"OK: no secret pattern in {scanned} files{history}.")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
